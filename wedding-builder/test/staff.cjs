const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const ctx = await browser.newContext({ viewport: { width: 1400, height: 1000 } });
  const dash = await ctx.newPage();
  await dash.goto('http://localhost:8791/test/opener.html');
  const [builder] = await Promise.all([ctx.waitForEvent('page'), dash.click('#open')]);
  await builder.waitForSelector('#barPrice'); 
  await builder.waitForFunction(() => { const b = document.querySelector('#addBtn'); return b && !b.disabled; }, null, { timeout: 60000 });
  console.log('btn:', await builder.textContent('#addBtn'), '| head3:', await builder.textContent('#wrHead3 .wr__h-v'), '| head4:', await builder.textContent('#wrHead4 .wr__h-v'));
  await builder.click('#wrHead3'); await builder.waitForTimeout(300);
  console.log('width chips:', await builder.$$eval('#widthChips .wr__chip', (e) => e.length), 'first/last:', await builder.$$eval('#widthChips .wr__chip', (e) => e[0].textContent + '/' + e[e.length - 1].textContent));
  await builder.click('#wrHead5'); await builder.waitForTimeout(300);
  console.log('staff line:', await builder.textContent('#staffLine'));
  await builder.screenshot({ path: 'shot-staff.png' });
  await builder.click('#addBtn'); await builder.waitForTimeout(800);
  console.log('status:', await builder.textContent('#status'));
  console.log('dashboard got:', (await dash.textContent('#out')).slice(0, 700));
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
